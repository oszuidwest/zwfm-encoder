package util

import (
	"crypto/pbkdf2"
	"crypto/rand"
	"crypto/sha256"
	"crypto/subtle"
	"encoding/base64"
	"errors"
	"strings"
)

const passwordHashPrefix = "$pbkdf2-sha256$600000$" //nolint:gosec // G101: format identifier and work factor, not a credential.

// HashPassword returns a salted PBKDF2-HMAC-SHA256 password hash.
func HashPassword(password string) (string, error) {
	salt := make([]byte, 16)
	if _, err := rand.Read(salt); err != nil {
		return "", err
	}
	key, err := pbkdf2.Key(sha256.New, password, salt, 600_000, 32)
	if err != nil {
		return "", err
	}
	return passwordHashPrefix + base64.RawStdEncoding.EncodeToString(salt) + "$" + base64.RawStdEncoding.EncodeToString(key), nil
}

func parsePasswordHash(encoded string) (salt, key []byte, err error) {
	suffix, ok := strings.CutPrefix(encoded, passwordHashPrefix)
	saltText, keyText, found := strings.Cut(suffix, "$")
	if !ok || !found || len(saltText) != 22 || len(keyText) != 43 {
		return nil, nil, errors.New("must be a PBKDF2-SHA256 hash generated by -hash-password")
	}
	salt, saltErr := base64.RawStdEncoding.Strict().DecodeString(saltText)
	key, keyErr := base64.RawStdEncoding.Strict().DecodeString(keyText)
	if saltErr != nil || keyErr != nil || len(salt) != 16 || len(key) != 32 {
		return nil, nil, errors.New("invalid password hash encoding")
	}
	return salt, key, nil
}

// ValidatePasswordHash checks the encoding and fixed work factor without deriving a key.
func ValidatePasswordHash(encoded string) error {
	_, _, err := parsePasswordHash(encoded)
	return err
}

// VerifyPasswordHash reports whether password matches a supported encoded hash.
func VerifyPasswordHash(password, encoded string) bool {
	salt, expected, err := parsePasswordHash(encoded)
	if err != nil {
		return false
	}
	key, err := pbkdf2.Key(sha256.New, password, salt, 600_000, 32)
	return err == nil && subtle.ConstantTimeCompare(key, expected) == 1
}
